               ADDRB(7 DOWNTO 0) <= state( 87 DOWNTO 80 );
           WHEN 6 =>
               ADDRA(7 DOWNTO 0) <= state( 111 DOWNTO 104 );
               ADDRB(7 DOWNTO 0) <= state( 103 DOWNTO 96 );
           WHEN 7 =>
               ADDRA(7 DOWNTO 0) <= state( 127 DOWNTO 120 );
               ADDRB(7 DOWNTO 0) <= state( 119 DOWNTO 112 );
	       WHEN 8 =>
	           sub_bytes_over <= '1';
	end case;  
	end if;
end process;

