  process (clk, rst) is

    variable shift_reg_output_var : unsigned(127 downto 0);

  begin

    if (rst = '0') then
      shift_reg_output <= (others => '0');
      sub_bytes_over   <= '0';
      addra            <= (others => '0');
      addrb            <= (others => '0');
    -- DOA <= (OTHERS => '0');
    -- DOB <= (OTHERS => '0');
    elsif rising_edge(clk) then
      sub_bytes_over <= '0';

      shift_reg_output_var                 := shift_reg_output srl 16;
      shift_reg_output_var(127 DOWNTO 120) := unsigned(doa);
      shift_reg_output_var(119 DOWNTO 112) := unsigned(dob);
      shift_reg_output                     <= shift_reg_output_var;

      case counter is

        when 0 =>

          addra(7 DOWNTO 0) <= state( 15 downto 8);
          addrb(7 DOWNTO 0) <= state( 7 downto 0);

        when 1 =>

          addra(7 DOWNTO 0) <= state( 31 downto 24);
