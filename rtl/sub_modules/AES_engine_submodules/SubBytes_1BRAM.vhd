          addrb(7 DOWNTO 0) <= state( 103 downto 96);

        when 7 =>

          addra(7 DOWNTO 0) <= state( 127 downto 120);
          addrb(7 DOWNTO 0) <= state( 119 downto 112);

        when 8 =>

          sub_bytes_over <= '1';

      end case;

    end if;

  end process;

  addra (10 DOWNTO 8) <= (others => '0');
  addrb (10 DOWNTO 8) <= (others => '0');

  output_state <= std_logic_vector(shift_reg_output);

